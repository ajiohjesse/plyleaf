const root = new URL("../node_modules/@phosphor-icons/core/assets/", import.meta.url);

function write(used: Record<string, Weight[]>, file: string) {
  const out: string[] = [];
  for (const [name, weights] of Object.entries(used)) {
    for (const weight of weights) {
      const svg = readFileSync(new URL(`${weight}/${name}-${weight}.svg`, root), "utf8");
      const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
      const paths = [...inner.matchAll(/<path d="([^"]+)"(?: opacity="([\d.]+)")?\/>/g)];
      if (paths.map((m) => m[0]).join("") !== inner) throw new Error(`${name} (${weight}) has more than plain paths`);
      const list = paths.map(([, d, opacity]) => (opacity ? `{ d: "${d}", faint: true }` : `{ d: "${d}" }`));
      out.push(`  "${name}:${weight}": [${list.join(", ")}],`);
    }
  }
  const lines = [
    "// Generated by scripts/icons.ts from @phosphor-icons/core (MIT). Don't edit; run `pnpm icons`.",
    'import type { Glyphs } from "./glyph";',
    "",
    "export const glyphs: Glyphs = {",
    ...out,
    "};",
    "",
  ];
  writeFileSync(new URL(`../src/components/icons/${file}`, import.meta.url), lines.join("\n"));
  console.log(`Wrote ${out.length} glyphs to ${file}.`);
}

write(UI, "glyphs.ts");
